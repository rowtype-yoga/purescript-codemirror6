import { EditorState } from "@codemirror/state";
import * as View from "@codemirror/view";
import * as Commands from "@codemirror/commands";
import * as Language from "@codemirror/language";
import { Tag, tags } from "@lezer/highlight";
import { oneDark as darkTheme } from "@codemirror/theme-one-dark";
import * as Lint from "@codemirror/lint";
import * as Autocomplete from "@codemirror/autocomplete";

export const eatSpace = stream => () => stream.eatSpace();
export const match = regex => stream => () => !!stream.match(regex);
export const next = stream => () => { stream.next(); };
export const current = stream => () => stream.current();
export const defineStreamLanguage = parser => Language.StreamLanguage.define(parser);
export const tag = name => tags[name];
export const defineTag = () => Tag.define();
export const defineHighlightStyle = specs => Language.HighlightStyle.define(specs);
export const syntaxHighlighting = style => Language.syntaxHighlighting(style);
export const lineNumbers = View.lineNumbers();
export const highlightActiveLineGutter = View.highlightActiveLineGutter();
export const history = Commands.history();
export const drawSelection = View.drawSelection();
export const bracketMatching = Language.bracketMatching();
export const indentOnInput = Language.indentOnInput();
export const rectangularSelection = View.rectangularSelection();
export const highlightActiveLine = View.highlightActiveLine();
export const defaultKeymap = Commands.defaultKeymap;
export const historyKeymap = Commands.historyKeymap;
export const indentWithTab = Commands.indentWithTab;
export const keymap = bindings => View.keymap.of(bindings);
export const lintGutter = Lint.lintGutter();
export const oneDark = darkTheme;
export const theme = spec => View.EditorView.theme(spec);
export const updateListener = callback => View.EditorView.updateListener.of(callback);
export const docChanged = update => update.docChanged;
export const updateState = update => update.state;
export const createState = config => EditorState.create(config);
export const createView = config => () => new View.EditorView(config);
export const state = view => () => view.state;
export const documentText = state => state.doc.toString();
export const documentLength = state => state.doc.length;
export const documentLines = state => state.doc.lines;
export const documentLine = number => state => state.doc.line(number);
export const replaceRange = view => changes => () => view.dispatch({ changes });
export const setDiagnostics = view => diagnostics => () => view.dispatch(Lint.setDiagnostics(view.state, diagnostics));
export const destroy = view => () => view.destroy();
export const autocompletion = config => Autocomplete.autocompletion(config);
export const completionKeymap = Autocomplete.completionKeymap;
